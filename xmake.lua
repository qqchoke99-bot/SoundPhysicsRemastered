add_rules("mode.release")

package("preloader")
    set_homepage("https://github.com/LiteLDev/preloader-android")
    set_description("Preloader Android")
    add_urls("https://github.com/LiteLDev/preloader-android.git")
    add_versions("1.5.25", "5d108da350ce3e7f13f51415f81e65344ecd5d14")
    add_deps("cmake")
    on_install("android", function (package)
        import("package.tools.cmake").install(package)
    end)
package_end()

add_requires("preloader 1.5.25")
add_requires("fmt")
target("SPP-Bedrock")
    set_kind("shared")
    set_languages("c++20")
    set_basename("SPPBedrock")
    add_files("src/main.cpp", "src/spp/*.cpp", "src/fmod/*.cpp", "src/mc/*.cpp")
    add_includedirs("include", "src")
    add_packages("preloader", "fmt")
    if is_plat("android") then
        set_runtimes("c++_static")
        add_cxflags("-fPIC", "-Oz", "-fexceptions", "-w", "-fvisibility=hidden")
        add_cxxflags("-fno-rtti")
        add_shflags("-Wl,--gc-sections", "-flto", "-Wl,-z,max-page-size=16384", "-Wl,--no-undefined")
        add_syslinks("log", "dl", "m", "c")
    end
